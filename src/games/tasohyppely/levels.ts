/*
 * The three levels as text maps, one character per tile (48 × 48 in game
 * space). Each level is a row of chunks side by side; chunks are aligned at
 * the bottom, so a short chunk simply has open sky above it. Play-testing
 * changes are made here: move, add or remove characters.
 *
 *   .  empty                    #  solid ground or wall
 *   =  platform (jump up through it, stand on it, ↓ + Space drops through)
 *   C  crumbling floor (gives way soon after it is stepped on, comes back later)
 *   ~  track of a platform moving sideways (the platform is 2 tiles wide)
 *   :  track of a platform moving up and down (the column of its left tile)
 *   P  swinging blade, hanging from this tile
 *   S  start (feet at the bottom of the tile)     G  gate at the end of the level
 *   B  left edge of the head witch's arena (last level)
 *   i  candle    h  candle that drops half a heart    u  candle that drops a whip upgrade
 *   Enemies: z zombie, b bat, r raven, a armour, s flaming skull, k spider,
 *            o will-o'-the-wisp, m poison mushroom, f wolf
 *
 * Walking enemies, candles on the ground and the start need ground under the
 * tile they are in. A candle one row above the walking row is hit standing;
 * two rows up it needs a jump or an upward lash.
 *
 * `climb` marks a chunk where the way goes up or down (Pasi 21.10.: climbing
 * sections): the rows are the surfaces the climb starts and ends on, counted
 * from the top of the chunk. Distance points follow the climb there.
 */

export type Theme = 'hautausmaa' | 'linna' | 'metsa';

export interface ChunkDef {
  rows: string[];
  climb?: [fromRow: number, toRow: number];
}

export interface LevelDef {
  name: string;
  theme: Theme;
  chunks: ChunkDef[];
}

